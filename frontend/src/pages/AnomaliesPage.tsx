import { useState, useEffect } from 'react'
import {
  Activity,
  AlertTriangle,
  CheckCircle2,
  TrendingUp,
  X,
} from 'lucide-react'
import {
  CartesianGrid,
  Line,
  LineChart,
  ResponsiveContainer,
  Tooltip,
  XAxis,
  YAxis,
} from 'recharts'
import { api, getErrorMessage, AnomalyItem } from '../api'
import {
  PageHeader,
  StateMessage,
  EmptyState,
  StatusBadge,
  MetricCard,
  Modal,
  tooltipStyle,
} from '../components/Common'

export default function AnomaliesPage() {
  const [anomalies, setAnomalies] = useState<AnomalyItem[]>([])
  const [institution, setInstitution] = useState('')
  const [programme, setProgramme] = useState('')
  const [year, setYear] = useState('')
  const [history, setHistory] = useState<any>(null)
  const [loadingHistory, setLoadingHistory] = useState(false)
  const [dismissingId, setDismissingId] = useState<number | null>(null)
  const [dismissReasonInput, setDismissReasonInput] = useState('')
  const [loading, setLoading] = useState(true)
  const [error, setError] = useState('')

  const load = () => {
    setLoading(true)
    setError('')
    api
      .get<{ items?: AnomalyItem[]; anomalies?: AnomalyItem[] }>('/analytics/anomalies')
      .then((anomRes) => {
        setAnomalies(anomRes.data.items || anomRes.data.anomalies || [])
      })
      .catch((e: unknown) => setError(getErrorMessage(e)))
      .finally(() => setLoading(false))
  }

  useEffect(() => {
    load()
  }, [])

  const institutions = [...new Set(anomalies.map((a) => a.institution_name || a.institution_id).filter(Boolean))]
  const programmes = [...new Set(anomalies.map((a) => a.programme_name || a.programme_id).filter(Boolean))]
  const years = [...new Set(anomalies.map((a) => a.academic_year).filter(Boolean))]

  const filtered = anomalies.filter((item) => {
    if (institution && (item.institution_name !== institution && item.institution_id !== institution))
      return false
    if (programme && (item.programme_name !== programme && item.programme_id !== programme))
      return false
    if (year && item.academic_year !== year) return false
    return true
  })

  const flaggedCount = anomalies.filter((a) => !a.dismissed).length
  const dismissedCount = anomalies.filter((a) => a.dismissed).length

  const viewHistory = async (item: AnomalyItem) => {
    setLoadingHistory(true)
    setHistory(null)
    try {
      const res = await api.get(`/analytics/historical/${encodeURIComponent(item.institution_id)}/${encodeURIComponent(item.programme_id)}`)
      setHistory(res.data)
    } catch (e) {
      alert(getErrorMessage(e))
    } finally {
      setLoadingHistory(false)
    }
  }

  const handleDismissSubmit = async (e: React.FormEvent) => {
    e.preventDefault()
    if (!dismissingId || !dismissReasonInput.trim()) return
    try {
      await api.patch(`/analytics/anomalies/${dismissingId}/dismiss`, {
        reason: dismissReasonInput.trim(),
      })
      setDismissingId(null)
      setDismissReasonInput('')
      load()
    } catch (err) {
      alert(getErrorMessage(err))
    }
  }

  return (
    <>
      <PageHeader
        eyebrow="APAAR-FUSE STATISTICAL ENGINE"
        title="Historical Anomaly Analysis"
        description="Z-score statistical deviation model evaluating sudden intake surges against 3-year baseline moving averages."
      />

      {/* Metric Cards */}
      <div className="metric-grid">
        <MetricCard
          label="Total Findings"
          value={anomalies.length}
          caption="Statistical deviations identified across all cohorts"
          icon={Activity}
          tone="blue"
        />
        <MetricCard
          label="Active Flags"
          value={flaggedCount}
          caption="Awaiting human reviewer investigation"
          icon={AlertTriangle}
          tone="amber"
        />
        <MetricCard
          label="Dismissed with Justification"
          value={dismissedCount}
          caption="Legitimate expansion verified by regulatory officer"
          icon={CheckCircle2}
          tone="green"
        />
        <MetricCard
          label="Detection Method"
          value="Z-Score Baseline"
          caption="Investigative signal only — does not imply fraud"
          icon={TrendingUp}
          tone="slate"
        />
      </div>

      <section className="panel table-panel">
        <div className="table-toolbar">
          <div>
            <h2>Historical Anomaly Results</h2>
            <p className="subheading">Counts and explanations are generated by the statistical engine</p>
          </div>

          <div className="filter-row compact-filters">
            <select
              aria-label="Filter institution"
              value={institution}
              onChange={(e) => {
                setInstitution(e.target.value)
                setProgramme('')
              }}
            >
              <option value="">All institutions</option>
              {institutions.map((i) => (
                <option key={i} value={i}>
                  {i}
                </option>
              ))}
            </select>

            <select
              aria-label="Filter programme"
              value={programme}
              onChange={(e) => setProgramme(e.target.value)}
            >
              <option value="">All programmes</option>
              {programmes.map((p) => (
                <option key={p} value={p}>
                  {p}
                </option>
              ))}
            </select>

            <select
              aria-label="Filter year"
              value={year}
              onChange={(e) => setYear(e.target.value)}
            >
              <option value="">All years</option>
              {years.map((y) => (
                <option key={y} value={y}>
                  {y}
                </option>
              ))}
            </select>
          </div>
        </div>

        {error ? (
          <StateMessage error={error} retry={load} />
        ) : loading ? (
          <StateMessage />
        ) : filtered.length ? (
          <div className="table-scroll">
            <table>
              <thead>
                <tr>
                  <th>Institution</th>
                  <th>Programme</th>
                  <th>Year</th>
                  <th>Admitted</th>
                  <th>Approved</th>
                  <th>Surge / Z-Score</th>
                  <th>Statistical Explanation</th>
                  <th>Status</th>
                  <th>Reviewer Disposition</th>
                  <th>Action</th>
                </tr>
              </thead>
              <tbody>
                {filtered.map((item) => (
                  <tr key={item.id}>
                    <td><strong>{item.institution_name || item.institution_id}</strong></td>
                    <td>{item.programme_name || item.programme_id}</td>
                    <td>{item.academic_year}</td>
                    <td><b>{item.admitted_count}</b></td>
                    <td>{item.approved_intake ?? '—'}</td>
                    <td>
                      <span className="mono font-semibold" style={{ color: item.pct_change && item.pct_change > 30 ? '#DC2626' : 'inherit' }}>
                        +{item.pct_change ?? '—'}% (Z: {item.z_score ?? '—'})
                      </span>
                    </td>
                    <td style={{ maxWidth: '300px', whiteSpace: 'normal', fontSize: '12.5px', color: 'var(--muted)' }}>
                      {item.explanation || 'Admissions surge exceeds standard variance'}
                    </td>
                    <td>
                      <StatusBadge
                        label={item.dismissed ? 'DISMISSED' : 'FLAGGED'}
                        tone={item.dismissed ? 'green' : 'amber'}
                      />
                    </td>
                    <td style={{ fontSize: '12px' }}>
                      {item.dismissal_reason ? (
                        <span style={{ color: '#1B756B' }}>Reason: {item.dismissal_reason}</span>
                      ) : (
                        <span style={{ color: 'var(--muted)' }}>Pending reviewer reason</span>
                      )}
                    </td>
                    <td>
                      <div style={{ display: 'flex', gap: '6px' }}>
                        <button
                          className="button-small"
                          onClick={() => viewHistory(item)}
                        >
                          History
                        </button>
                        {!item.dismissed && (
                          <button
                            className="button-small button-outline"
                            onClick={() => {
                              setDismissingId(item.id)
                              setDismissReasonInput('')
                            }}
                          >
                            Dismiss
                          </button>
                        )}
                      </div>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        ) : (
          <EmptyState
            title="No anomalies match filters"
            message="No records matched the selected institution, programme, or year."
          />
        )}
      </section>

      {/* Historical Trend Chart Panel */}
      {(history || loadingHistory) && (
        <section className="panel history-panel" style={{ marginTop: '22px', padding: '24px' }}>
          <div className="panel-heading">
            <div>
              <h2>{history?.institution_name || 'Multi-Year Historical Trend'}</h2>
              <p>{history?.programme_name || 'Baseline comparison analysis'}</p>
            </div>
            <button className="icon-button" onClick={() => setHistory(null)} aria-label="Close">
              <X size={17} />
            </button>
          </div>

          {loadingHistory ? (
            <StateMessage />
          ) : history?.history?.length ? (
            <>
              <div className="baseline-note" style={{ display: 'flex', gap: '20px', padding: '12px 16px', background: 'var(--workspace)', borderRadius: '10px', marginBottom: '16px', fontSize: '13px' }}>
                <span><strong>Baseline Mean:</strong> {history.baseline_mean}</span>
                <span><strong>Method:</strong> {history.detection_method}</span>
                <span style={{ color: 'var(--muted)' }}>
                  Sample size: {history.history.length} years (Small samples do not imply statistical certainty)
                </span>
              </div>

              <div className="chart-wrap" style={{ height: '240px', marginBottom: '16px' }}>
                <ResponsiveContainer width="100%" height="100%">
                  <LineChart data={history.history}>
                    <CartesianGrid stroke="#e9edf6" strokeDasharray="3 4" vertical={false} />
                    <XAxis dataKey="academic_year" tickLine={false} axisLine={false} tick={{ fill: '#7a859e', fontSize: 12 }} />
                    <YAxis tickLine={false} axisLine={false} tick={{ fill: '#7a859e', fontSize: 12 }} />
                    <Tooltip contentStyle={tooltipStyle} cursor={{ stroke: '#cfd6e6' }} />
                    <Line
                      type="monotone"
                      dataKey="admitted_count"
                      name="Historical admissions"
                      stroke="#1B756B"
                      strokeWidth={3}
                      dot={{ r: 5, fill: '#fff', strokeWidth: 2 }}
                    />
                    <Line
                      type="monotone"
                      dataKey={() => history.baseline_mean}
                      name="Baseline mean"
                      stroke="#F0B43A"
                      strokeDasharray="5 4"
                      dot={false}
                    />
                  </LineChart>
                </ResponsiveContainer>
              </div>

              <div className="table-scroll">
                <table>
                  <thead>
                    <tr>
                      <th>Academic Year</th>
                      <th>Admitted</th>
                      <th>Approved Intake</th>
                      <th>% Change</th>
                      <th>Z-Score</th>
                      <th>Explanation</th>
                    </tr>
                  </thead>
                  <tbody>
                    {history.history.map((row: any) => (
                      <tr key={row.id}>
                        <td>{row.academic_year}</td>
                        <td><b>{row.admitted_count}</b></td>
                        <td>{row.approved_intake ?? '—'}</td>
                        <td>{row.pct_change}%</td>
                        <td className="mono">{row.z_score}</td>
                        <td style={{ fontSize: '12.5px', color: 'var(--muted)' }}>{row.explanation || '—'}</td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            </>
          ) : (
            <EmptyState title="No historical data" message="No previous multi-year records were returned." />
          )}
        </section>
      )}

      {/* Dismissal Reason Modal */}
      {dismissingId && (
        <Modal
          title="Dismiss Statistical Anomaly"
          subtitle="Mandatory regulatory audit requirement: Explain why this intake surge is justified"
          onClose={() => setDismissingId(null)}
        >
          <form onSubmit={handleDismissSubmit}>
            <div className="form-group" style={{ marginBottom: '18px' }}>
              <label>Justification Reason</label>
              <textarea
                rows={3}
                required
                placeholder="e.g. AICTE approved special capacity expansion under National Mission 2026."
                value={dismissReasonInput}
                onChange={(e) => setDismissReasonInput(e.target.value)}
              />
            </div>
            <div style={{ display: 'flex', justifyContent: 'flex-end', gap: '10px' }}>
              <button
                type="button"
                className="button-secondary"
                onClick={() => setDismissingId(null)}
              >
                Cancel
              </button>
              <button
                type="submit"
                className="button-primary"
                disabled={!dismissReasonInput.trim()}
              >
                Confirm Dismissal
              </button>
            </div>
          </form>
        </Modal>
      )}
    </>
  )
}
